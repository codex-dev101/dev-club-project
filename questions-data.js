// Helper: Get all available subjects (standard + custom instructor packs)
function getCbtAllSubjects() {
  const list = [];
  
  // 1. Standard subjects from question bank
  (window.CBT_SUBJECTS_METADATA || []).forEach(sub => {
    const questions = window.CBT_QUESTION_BANK[sub.id] || [];
    list.push({
      id: sub.id,
      title: sub.title,
      icon: sub.icon,
      category: sub.category,
      desc: sub.desc,
      questionCount: questions.length,
      maxQuestions: questions.length,
      isCustom: false
    });
  });

  // 2. Custom instructor packs from Creator Studio
  try {
    const customPacks = JSON.parse(localStorage.getItem("cbt_custom_packs") || "[]");
    customPacks.forEach(pack => {
      if (pack && pack.id) {
        const qCount = Array.isArray(pack.questions) ? pack.questions.length : 0;
        list.push({
          id: pack.id,
          title: pack.title || "Custom Question Pack",
          icon: "fa-sliders",
          category: "Custom Instructor Pack",
          desc: pack.description || ("Created by " + (pack.creatorName || "Instructor") + " (" + (pack.creatorTag || "@teacher") + ")"),
          questionCount: qCount,
          maxQuestions: qCount,
          isCustom: true,
          creatorTag: pack.creatorTag || "@teacher",
          creatorName: pack.creatorName || "Instructor",
          durationMinutes: pack.durationMinutes || 30
        });
      }
    });
  } catch (e) {
    console.warn("Could not read custom packs:", e);
  }

  return list;
}

// Helper: Get subject details by ID
function getCbtSubjectById(subjectId) {
  const all = getCbtAllSubjects();
  return all.find(s => s.id === subjectId) || null;
}

// Helper: Get full question list for a subject
function getCbtQuestionsForSubject(subjectId) {
  let list = [];
  // Check standard bank
  if (window.CBT_QUESTION_BANK && window.CBT_QUESTION_BANK[subjectId]) {
    list = [...window.CBT_QUESTION_BANK[subjectId]];
  } else {
    // Check custom packs
    try {
      const customPacks = JSON.parse(localStorage.getItem("cbt_custom_packs") || "[]");
      const pack = customPacks.find(p => p.id === subjectId || p.subjectKey === subjectId);
      if (pack && Array.isArray(pack.questions)) {
        list = [...pack.questions];
      }
    } catch (e) {}
  }

  // Fallback to general knowledge
  if (list.length === 0 && window.CBT_QUESTION_BANK && window.CBT_QUESTION_BANK.general_knowledge) {
    list = [...window.CBT_QUESTION_BANK.general_knowledge];
  }

  return list.map((q, idx) => ({
    id: q.id || `${subjectId}_q${idx + 1}`,
    ...q
  }));
}

// Helper: Randomly sample requested number of questions without duplicates
function sampleCbtQuestions(subjectId, requestedCount) {
  const bank = getCbtQuestionsForSubject(subjectId);
  const eligibleCount = bank.length;
  const count = Math.min(requestedCount, eligibleCount);

  // Fisher-Yates shuffle
  const shuffled = [...bank];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}

